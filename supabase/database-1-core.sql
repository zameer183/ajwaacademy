CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- 1. COURSES TABLE
CREATE TABLE IF NOT EXISTS public.courses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  slug TEXT UNIQUE,
  category TEXT,
  level TEXT,
  description TEXT,
  image TEXT,
  thumbnail TEXT,
  price NUMERIC,
  original_price NUMERIC,
  duration TEXT,
  lesson_count INTEGER DEFAULT 0,
  rating NUMERIC DEFAULT 5.0,
  reviews_count INTEGER DEFAULT 0,
  enrolled_students INTEGER DEFAULT 0,
  instructor_name TEXT,
  instructor_avatar TEXT,
  tags JSONB DEFAULT '[]'::jsonb,
  features JSONB DEFAULT '[]'::jsonb,
  curriculum JSONB DEFAULT '[]'::jsonb,
  outline TEXT,
  progress_enabled BOOLEAN DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE public.courses ENABLE ROW LEVEL SECURITY;
DO $$ BEGIN
  CREATE POLICY "Public read courses" ON public.courses FOR SELECT TO anon, authenticated USING (true);
EXCEPTION WHEN duplicate_object THEN null; END $$;

-- 2. TRIAL REQUESTS TABLE (LEADS)
CREATE TABLE IF NOT EXISTS public.trial_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users ON DELETE SET NULL,
  course_id BIGINT,
  course_title TEXT,
  name TEXT NOT NULL,
  email TEXT,
  whatsapp TEXT,
  timezone TEXT,
  country TEXT,
  message TEXT,
  status TEXT DEFAULT 'pending',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE public.trial_requests ENABLE ROW LEVEL SECURITY;
DO $$ BEGIN
  CREATE POLICY "Anon insert trial_requests" ON public.trial_requests FOR INSERT TO anon, authenticated WITH CHECK (true);
EXCEPTION WHEN duplicate_object THEN null; END $$;
DO $$ BEGIN
  CREATE POLICY "Admin read trial_requests" ON public.trial_requests FOR SELECT TO authenticated USING (true);
EXCEPTION WHEN duplicate_object THEN null; END $$;

-- 3. LIBRARY ITEMS TABLE
CREATE TABLE IF NOT EXISTS public.library_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  category TEXT,
  type TEXT,
  author TEXT,
  description TEXT,
  image TEXT,
  file_url TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE public.library_items ENABLE ROW LEVEL SECURITY;
DO $$ BEGIN
  CREATE POLICY "Public read library_items" ON public.library_items FOR SELECT TO anon, authenticated USING (true);
EXCEPTION WHEN duplicate_object THEN null; END $$;

